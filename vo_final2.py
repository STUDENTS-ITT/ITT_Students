def select_strongest(keypoints, n):
    """Аналог selectStrongest: N точек с наибольшим откликом."""
    if len(keypoints) <= n:
        return list(keypoints)
    return sorted(keypoints, key=lambda k: -k.response)[:n]


def _grid_cells(xy, image_size, num_points):
    """
    Номера ячеек сетки для точек - ядро selectPoints из FeaturePointsImpl.m.

    image_size здесь - [ширина, высота] (MATLAB переставляет размеры перед
    вызовом). Координаты точек - в системе MATLAB, с началом в 1.
    Возвращает (плоские номера ячеек, число ячеек по вертикали).
    """
    aspect = image_size[0] / image_size[1]
    h = max(int(np.floor(np.sqrt(num_points / aspect))), 1)
    w = max(int(np.floor(h * aspect)), 1)
    n_bins = np.array([w, h], dtype=np.int64)
    grid_step = np.asarray(image_size, dtype=np.float64) / (n_bins + 1)

    which = np.minimum(np.floor(xy / grid_step).astype(np.int64) + 1, n_bins)
    return (which[:, 0] - 1) * h + (which[:, 1] - 1), h


def _select_points_grid(xy, metric, image_size, num_points):
    """
    Порт selectPoints из FeaturePointsImpl.m: по одной сильнейшей точке
    на ячейку сетки. Возвращает булеву маску отобранных точек.
    """
    n = len(xy)
    if num_points == 1:
        keep = np.zeros(n, dtype=bool)
        keep[int(np.argmax(metric))] = True
        return keep

    flat, _ = _grid_cells(xy, image_size, num_points)

    # В каждой ячейке остаётся точка с максимальной метрикой. MATLAB идёт по
    # точкам по порядку и заменяет при строгом превосходстве - то же самое
    # даёт устойчивая сортировка по убыванию метрики с выбором первой.
    # np.unique по отсортированным номерам ячеек делает это без цикла Python.
    order = np.argsort(-metric, kind='stable')
    _, first = np.unique(flat[order], return_index=True)

    keep = np.zeros(n, dtype=bool)
    keep[order[first]] = True
    return keep


def select_uniform(keypoints, n, image_shape):
    """
    Порт selectUniform из FeaturePointsImpl.m.

    Сетка примерно из N ячеек, из каждой берётся сильнейшая точка; если
    набралось меньше N, отобранные точки исключаются и проход повторяется.

    Точки сортируются по метрике ОДИН раз на кадр, а не на каждом проходе:
    подмножество уже отсортированного массива остаётся отсортированным.
    На 27 тысячах точек это 8 мс вместо 32 при том же результате.
    """
    if len(keypoints) <= n:
        return list(keypoints)

    # MATLAB: imageSize = imageSize([2,1]) -> [ширина, высота]
    image_size = np.array([float(image_shape[1]), float(image_shape[0])])
    # Координаты MATLAB начинаются с 1. KeyPoint_convert работает в C++.
    xy_all = cv2.KeyPoint_convert(keypoints).astype(np.float64) + 1.0
    metric_all = np.fromiter((kp.response for kp in keypoints),
                             dtype=np.float64, count=len(keypoints))

    order = np.argsort(-metric_all, kind='stable')
    xy_sorted = xy_all[order]

    selected = []
    alive = np.arange(len(keypoints))      # индексы в xy_sorted, по убыванию метрики
    while len(selected) < n and alive.size:
        need = n - len(selected)
        flat, _ = _grid_cells(xy_sorted[alive], image_size, need)
        _, first = np.unique(flat, return_index=True)   # alive уже упорядочен
        if first.size == 0:
            break
        take = np.zeros(alive.size, dtype=bool)
        take[first] = True
        selected.extend(alive[take].tolist())
        alive = alive[~take]

    return [keypoints[order[i]] for i in selected[:n]]


