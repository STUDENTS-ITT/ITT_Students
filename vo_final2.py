# Оценка траектории по последовательности монокулярных кадров.
# Поступательное движение монокулярной камеры определяется только с точностью
# до масштаба: cfg['VO']['TranslationScale'] задаёт длину КАЖДОГО успешного
# шага. Длина пути поэтому равна (число успешных шагов) x TranslationScale и
# не является измерением - это принципиальное свойство метода, а не порта.
# Накопление позы (как в MATLAB и в отчёте):
#     p_k = p_{k-1} + R_{k-1} * s * t_rel
#     R_k = R_{k-1} * R_rel


