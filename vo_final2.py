def normalize_source(source):
    """file:// разворачиваем в обычный путь - OpenCV читает его надёжнее."""
    text = str(source)
    if text.lower().startswith('file://'):
        text = text[7:].lstrip('/')
        if len(text) > 1 and text[1] == ':':
            return text                       # C:/... на Windows
        return '/' + text                     # абсолютный путь в unix
    return text


