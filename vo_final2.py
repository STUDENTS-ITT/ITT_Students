# Порт +vo/preprocessFrame.m и +vo/blankOsd.m
# Приведение кадра к полутоновому uint8, компенсация дисторсии, заливка
# областей экранной индикации (OSD).
# Зачем заливать OSD (комментарий из оригинала, он важен для понимания):
# пороги detectHarrisFeatures и detectFASTFeatures задаются параметром
# MinQuality, который отсчитывается ОТ МАКСИМУМА отклика по кадру. Белый текст
# OSD на тёмной подложке даёт отклик на порядки сильнее малоконтрастного
# асфальта, поэтому планка поднимается так высоко, что вся реальная сцена
# оказывается ниже неё. На исходном материале Harris и FAST находили 899 и 1517
# точек, и все до единой лежали на OSD.


def to_gray_uint8(raw):
    """rgb2gray + приведение к uint8 (как в preprocessFrame.m)."""
    img = raw
    if img.ndim == 3:
        if img.shape[2] == 4:
            img = cv2.cvtColor(img, cv2.COLOR_BGRA2GRAY)
        else:
            # OpenCV BGR2GRAY использует те же веса Rec.601, что и MATLAB
            # rgb2gray: 0.299 R + 0.587 G + 0.114 B.
            img = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

    if img.dtype == np.uint8:
        return img
    if np.issubdtype(img.dtype, np.floating):
        if img.size == 0:
            return img.astype(np.uint8)
        lo, hi = float(np.nanmin(img)), float(np.nanmax(img))
        if lo >= 0.0 and hi <= 1.0:
            return np.clip(img * 255.0, 0, 255).astype(np.uint8)   # im2uint8
        if hi > lo:
            return np.clip((img - lo) / (hi - lo) * 255.0, 0, 255).astype(np.uint8)
        return np.zeros(img.shape, np.uint8)                        # mat2gray
    if img.dtype == np.uint16:
        return (img // 257).astype(np.uint8)
    return cv2.normalize(img, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)


def osd_mask_image(shape, cfg):
    """Булева маска областей OSD по прямоугольникам [x, y, w, h]."""
    rects = cfg['Preprocess'].get('OsdMask')
    if not rects:
        return None
    h, w = shape[:2]
    mask = np.zeros((h, w), dtype=bool)
    for x, y, rw, rh in rects:
        x0 = max(0, int(np.floor(x)))
        y0 = max(0, int(np.floor(y)))
        x1 = min(w, x0 + int(np.ceil(rw)) + 1)
        y1 = min(h, y0 + int(np.ceil(rh)) + 1)
        if x1 > x0 and y1 > y0:
            mask[y0:y1, x0:x1] = True
    return mask if mask.any() else None


# Маска OSD и полоса размытия зависят только от размера кадра и настроек,
# то есть одинаковы для всех кадров прогона. Считаем их один раз.
_OSD_CACHE = {}


def _osd_geometry(shape, cfg):
    """(маска OSD, полоса размытия по её границе) с запоминанием по размеру кадра."""
    pre = cfg['Preprocess']
    sigma = float(pre.get('OsdBlurSigma', 4.0))
    radius = int(pre.get('OsdEdgeRadius', 6))
    rects = pre.get('OsdMask')
    key = (shape[0], shape[1], radius,
           tuple(tuple(r) for r in rects) if rects else None)

    cached = _OSD_CACHE.get(key)
    if cached is not None:
        return cached

    mask = osd_mask_image(shape, cfg)
    edge_band = None
    if mask is not None and sigma > 0 and radius > 0:
        k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE,
                                      (2 * radius + 1, 2 * radius + 1))
        m8 = mask.astype(np.uint8)
        edge_band = (cv2.dilate(m8, k) > 0) & (cv2.erode(m8, k) == 0)

    _OSD_CACHE.clear()          # прогон идёт с одним размером кадра
    _OSD_CACHE[key] = (mask, edge_band)
    return mask, edge_band


def blank_osd(image, cfg):
    """
    Замена областей OSD ровным фоном (средней яркостью кадра) с размытием
    границы, чтобы на ступеньке заливки не появились новые углы.
    """
    mask, edge_band = _osd_geometry(image.shape, cfg)
    if mask is None:
        return image

    out = image.copy()
    fill = np.uint8(round(float(image.mean())))
    out[mask] = fill

    if edge_band is not None:
        sigma = float(cfg['Preprocess'].get('OsdBlurSigma', 4.0))
        blurred = cv2.GaussianBlur(out, (0, 0), sigma)
        out[edge_band] = blurred[edge_band]
    return out


def preprocess_frame(raw, calib, cfg):
    """Полутоновый uint8-кадр, готовый к детектированию."""
    img = to_gray_uint8(raw)

    pre = cfg['Preprocess']
    if pre.get('Undistort') and calib is not None and calib.has_distortion:
        try:
            K = calib.Intrinsics.K
            img = cv2.undistort(img, K, calib.Intrinsics.distortion, None, K)
        except cv2.error as exc:
            print(f'[ПРЕДУПРЕЖДЕНИЕ] Не удалось исправить дисторсию: {exc}')

    if pre.get('UseCLAHE'):
        clahe = cv2.createCLAHE(
            clipLimit=float(pre.get('ClaheClipLimit', 2.0)),
            tileGridSize=tuple(pre.get('ClaheTileGrid', (8, 8))))
        img = clahe.apply(img)

    return blank_osd(img, cfg)


