class FrameSelector:
    """
    Выбор следующего обрабатываемого кадра.

    ЗАЧЕМ. Постоянный шаг по кадрам - всегда компромисс под одну съёмку.
    Качество оценки движения определяется не числом пропущенных кадров, а
    ОТНОСИТЕЛЬНЫМ СМЕЩЕНИЕМ СЦЕНЫ между обработанными кадрами; рабочая
    область - примерно 5..15 % ширины кадра.

    Мало смещения - полезный сигнал тонет в шуме сопоставления, и вдобавок
    шагов становится много, а ошибка накапливается на каждом. Много - теряется
    перекрытие кадров, и сопоставление дескрипторов рассыпается.

    Смещение зависит от скорости, высоты, фокусного расстояния и частоты
    кадров сразу, поэтому в кадрах его не задать. Здесь фиксируется не шаг,
    а ЦЕЛЬ по смещению, а шаг подстраивается обратной связью:

        шаг_след = шаг * цель / измеренное_смещение

    с демпфированием и ограничением сверху и снизу.

    Второй контур - по угловой скорости: разворот теряет перекрытие быстрее,
    чем поступательное движение. Третий - аварийный откат при неудачном
    сопоставлении (метод shrink).
    """

    def __init__(self, cfg, frame_width):
        sel = cfg['FrameSelect']
        self.mode = str(sel.get('Mode', 'adaptive')).lower()
        self.width = float(frame_width)
        self.min_step = max(1, int(sel.get('MinStep', 1)))
        self.max_step = max(self.min_step, int(sel.get('MaxStep', 120)))
        self.target = float(sel.get('TargetShiftPct', 10.0)) / 100.0
        self.damping = min(max(float(sel.get('Damping', 0.5)), 0.0), 1.0)
        self.max_growth = float(sel.get('MaxGrowth', 1.5))

        self.turn_limit = math.radians(float(sel.get('TurnLimitDps', 3.0)))
        self.turn_reject = math.radians(float(sel.get('TurnRejectDps', 0.0)))
        self.turn_reject_min = math.radians(
            float(sel.get('TurnRejectMinDeg', 4.0)))
        self.turn_noise_floor = math.radians(
            float(sel.get('TurnNoiseFloorDeg', 1.0)))
        self.turn_gate_frac = float(sel.get('TurnGateFraction', 0.3))

        self.fixed_step = max(1, int(cfg['FrameStep']))
        # Шаг ведётся ВЕЩЕСТВЕННЫМ: иначе из значения 1 он не может вырасти,
        # потому что round(1 * 1.25) снова даёт 1, и регулятор залипает на
        # минимуме после первого же резкого манёвра.
        self._step_f = float(self.fixed_step if self.mode == 'fixed'
                             else min(max(int(sel.get('StartStep', 5)),
                                          self.min_step), self.max_step))

    @property
    def step(self):
        """Целый шаг по кадрам для текущей итерации."""
        return int(min(max(round(self._step_f), self.min_step), self.max_step))

    def describe(self):
        if self.mode == 'fixed':
            return f'Выбор кадров: постоянный шаг {self.fixed_step}'
        return (f'Выбор кадров: адаптивный, цель по смещению сцены '
                f'{100 * self.target:.0f} % ширины кадра, шаг в пределах '
                f'{self.min_step}..{self.max_step}, старт {self.step}')

    def can_shrink(self):
        return self.mode != 'fixed' and self.step > self.min_step

    def shrink(self):
        """Аварийный откат: не сошлось - берём кадр ближе."""
        self._step_f = max(float(self.min_step), self._step_f / 2.0)

    def too_sharp(self, turn_rad, dt):
        """
        Манёвр слишком резкий для такого шага?

        По умолчанию ВЫКЛЮЧЕНО (TURN_REJECT_DPS = 0) и включать не стоит:
        при развороте отбраковка дробит шаг до минимума, и вместо одной оценки
        поворота на большой базе получаются сотни оценок на базе в два-три
        пикселя, где сигнал тонет в шуме.
        """
        if self.mode == 'fixed' or dt <= 0 or self.turn_reject <= 0:
            return False
        turn = abs(float(turn_rad))
        return turn / dt > self.turn_reject and turn > self.turn_reject_min

    def update(self, shift_px, turn_rad, dt, success):
        """Пересчёт шага по смещению сцены и угловой скорости."""
        if self.mode == 'fixed':
            self._step_f = float(self.fixed_step)
            return
        if not success:
            self.shrink()
            return

        frac = float(shift_px) / max(self.width, 1e-9)
        if frac <= 1e-6:
            # Камера практически стоит: наращиваем шаг осторожно, иначе
            # деление на почти ноль увело бы его сразу в потолок.
            gain = self.max_growth
        else:
            gain = self.target / frac

        # Ограничение включается, только когда оценка поворота достоверна:
        # сцена сместилась заметно (не меньше доли от цели) И сам поворот
        # больше шума. Иначе шум на короткой базе не даёт шагу восстановиться
        # после разворота: он остаётся в минимуме до конца прогона.
        turn = abs(float(turn_rad))
        observable = frac >= self.turn_gate_frac * self.target
        if observable and turn > self.turn_noise_floor:
            rate = turn / max(float(dt), 1e-9)
            if rate > 1e-9:
                gain = min(gain, self.turn_limit / rate)

        gain = min(max(gain, 1.0 / self.max_growth), self.max_growth)
        gain = 1.0 + self.damping * (gain - 1.0)     # демпфирование

        self._step_f = min(max(self._step_f * gain, float(self.min_step)),
                           float(self.max_step))


class RotationCrop:
    """
    Состояние режима поворота и границы используемой части кадра.

    Порог задаётся на один ОБРАБОТАННЫЙ шаг, а не на кадр исходного видео:
    при прореживании и при адаптивном выборе кадров это разные величины.

    Режим включается, как только поворот превысил порог, и держится ещё
    DelaySteps шагов после того, как поворот снова стал меньше порога.
    Задержка нужна, чтобы на границе порога режим не переключался каждый шаг:
    иначе набор точек скачками менял бы состав, и траектория дёргалась бы.
    """

    def __init__(self, cfg):
        settings = cfg.get('RotationCrop') or {}
        self.enabled = bool(settings.get('Enable', False))
        # Порог хранится в радианах в СЕКУНДУ (см. update).
        self.threshold = math.radians(float(settings.get('ThresholdDps', 9.0)))
        self.delay = int(settings.get('DelaySteps', 2))
        self.rotation_cut = tuple(settings.get('RotationCut', (0, 0, 0, 0)))
        self.normal_cut = tuple(settings.get('NormalCut', (0, 0, 0, 0)))
        self.angle_source = str(settings.get('AngleSource', 'inplane')).lower()

        self.active = bool(settings.get('AtStart', False)) and self.enabled
        self.since_change = 0
        self.steps_active = 0
        self.last_angle = 0.0

    # ------------------------------------------------------------- геометрия
    def current_cut(self):
        """Доли (слева, справа, сверху, снизу), которые сейчас не используются."""
        if not self.enabled:
            return self.normal_cut
        return self.rotation_cut if self.active else self.normal_cut

    def bounds(self, image_shape):
        """Прямоугольник (x_min, x_max, y_min, y_max) в пикселях."""
        h, w = image_shape[:2]
        left, right, top, bottom = self.current_cut()
        return (w * float(left), w * (1.0 - float(right)),
                h * float(top), h * (1.0 - float(bottom)))

    def crop_fraction(self):
        """Какая доля площади кадра сейчас используется."""
        left, right, top, bottom = self.current_cut()
        return max(0.0, 1.0 - left - right) * max(0.0, 1.0 - top - bottom)

    # -------------------------------------------------------------- состояние
    @staticmethod
    def angle_from_rotation(R, source='inplane'):
        """
        Угол поворота между кадрами, радианы.

        'inplane' - поворот вокруг оптической оси камеры. Для надирной съёмки
                    это рыскание аппарата; в плоской модели он берётся прямо
                    из аффинной матрицы как atan2(M[1,0], M[0,0]).
        'total'   - полный угол матрицы поворота: acos((tr(R) - 1) / 2).
        """
        R = np.asarray(R, dtype=np.float64)
        if R.shape != (3, 3) or not np.all(np.isfinite(R)):
            return 0.0
        if source == 'total':
            cos_a = (np.trace(R) - 1.0) / 2.0
            return float(np.arccos(np.clip(cos_a, -1.0, 1.0)))
        return float(math.atan2(R[1, 0], R[0, 0]))

    def update(self, turn_rad, dt):
        """
        Учесть поворот очередного шага.

        turn_rad - поворот за шаг, радианы; dt - длительность шага, секунды.
        Сравнивается угловая СКОРОСТЬ, а не угол за шаг: при адаптивном выборе
        кадров шаг плавает от 1 до 120 кадров, и порог «градусов на шаг»
        означал бы совершенно разную резкость манёвра.
        """
        angle = float(turn_rad)
        self.last_angle = angle
        if not self.enabled:
            return angle

        rate = abs(angle) / max(float(dt), 1e-9)
        if rate > self.threshold:
            if not self.active:
                self.active = True
                self.since_change = 0
            self.since_change += 1
        elif self.active:
            self.since_change += 1
            if self.since_change > self.delay:
                self.active = False
                self.since_change = 0

        if self.active:
            self.steps_active += 1
        return angle


def reject_cropped_points(keypoints, crop, image_shape):
    """
    Убрать точки за границами используемой части кадра.

    Отбор идёт ПОСЛЕ детектирования, а не маской внутри детектора: так приём
    работает одинаково для всех семи связок, включая собственные реализации
    Harris и FAST, которые маску не принимают. Скорость детектирования это,
    разумеется, не снижает - обрезка здесь нужна для качества, а не для
    ускорения.
    """
    if crop is None or not crop.enabled or not keypoints:
        return keypoints, 0
    left, right, top, bottom = crop.current_cut()
    if left <= 0 and right <= 0 and top <= 0 and bottom <= 0:
        return keypoints, 0

    x_min, x_max, y_min, y_max = crop.bounds(image_shape)
    xy = cv2.KeyPoint_convert(keypoints).astype(np.float64)
    inside = ((xy[:, 0] >= x_min) & (xy[:, 0] <= x_max) &
              (xy[:, 1] >= y_min) & (xy[:, 1] <= y_max))
    kept = [keypoints[i] for i in np.nonzero(inside)[0].tolist()]
    return kept, int(len(keypoints) - len(kept))


def reject_osd_points(keypoints, cfg):
    """
    Удаление точек, попавших в область OSD (порт rejectOsdPoints.m).

    Точки на неподвижной относительно камеры графике совпадают между кадрами
    идеально и с нулевым смещением, поэтому RANSAC охотно объявляет их
    инлаерами, а оценка движения смещается к нулю.
    """
    rects = cfg['Preprocess'].get('OsdMask')
    if not rects or not keypoints:
        return keypoints, 0

    margin = float(cfg['Preprocess'].get('OsdMargin', 12))
    xy = cv2.KeyPoint_convert(keypoints).astype(np.float64)

    inside = np.zeros(len(keypoints), dtype=bool)
    for x, y, w, h in rects:
        inside |= ((xy[:, 0] >= x - margin) & (xy[:, 0] <= x + w + margin) &
                   (xy[:, 1] >= y - margin) & (xy[:, 1] <= y + h + margin))

    num_rejected = int(inside.sum())
    # Обход по номерам оставшихся точек вместо zip по всему списку:
    # на 27 тысячах точек это 1 мс вместо 5.
    kept = [keypoints[i] for i in np.nonzero(~inside)[0].tolist()]
    return kept, num_rejected


