def _sniff_delimiter(sample):
    for d in (',', ';', chr(9), '|'):
        if sample.count(d) >= 1:
            return d
    return None    # пробелы


ALT_ALIASES = ('alt', 'altitude', 'height', 'hgt', 'elevation', 'ele',
               'agl', 'asl', 'z', 'высота')
ALT_FRAME_ALIASES = ('frame', 'frameid', 'index', 'idx', 'sample', 'time',
                     't', 'timestamp', 'sec', 'кадр', 'время')


def _pick_altitude_column(header, requested, aliases):
    """Индекс колонки по явному указанию или по списку синонимов."""
    low = [h.strip().lower().lstrip('﻿') for h in header]

    if isinstance(requested, int):
        return requested
    req = str(requested or 'auto').strip().lower()
    if req and req != 'auto':
        if req.isdigit():
            return int(req)
        if req in low:
            return low.index(req)
        raise RuntimeError(
            f'Колонка "{requested}" не найдена. Заголовок: {", ".join(header)}')

    for alias in aliases:
        if alias in low:
            return low.index(alias)
    for i, name in enumerate(low):
        if any(alias in name for alias in aliases):
            return i
    return None


def _read_altitude_file(cfg, frame_ids):
    """Чтение высот из CSV или текстового файла с разделителями."""
    path = cfg['Altitude']['File']
    if not path or not os.path.exists(path):
        raise RuntimeError(f'Файл высот не найден: {path}')

    with open(path, 'r', encoding='utf-8-sig', errors='replace', newline='') as fh:
        lines = [ln for ln in fh.read().splitlines() if ln.strip()]
    if not lines:
        raise RuntimeError(f'Файл высот пуст: {path}')

    delim = _sniff_delimiter(lines[0])
    split = ((lambda s: [c.strip() for c in s.split(delim)]) if delim
             else (lambda s: s.split()))

    header = split(lines[0])
    has_header = any(re.search(r'[A-Za-zА-Яа-я]', c) for c in header)
    rows = lines[1:] if has_header else lines
    if not has_header:
        header = [f'col{i}' for i in range(len(header))]

    i_alt = _pick_altitude_column(header, cfg['Altitude'].get('Column', 'auto'),
                                  ALT_ALIASES)
    if i_alt is None:
        if len(header) == 1:
            i_alt = 0
        else:
            raise RuntimeError(
                f'В файле {path} не найдена колонка высоты. Укажите её явно: '
                f'ALTITUDE_COLUMN. Заголовок: {", ".join(header)}')

    i_frame = _pick_altitude_column(
        header, cfg['Altitude'].get('FrameColumn', 'auto'), ALT_FRAME_ALIASES)
    if i_frame == i_alt:
        i_frame = None

    keys, values = [], []
    for line in rows:
        cells = split(line)
        if i_alt >= len(cells):
            continue
        try:
            value = float(cells[i_alt])
        except ValueError:
            continue
        key = None
        if i_frame is not None and i_frame < len(cells):
            try:
                key = float(cells[i_frame])
            except ValueError:
                key = None
        values.append(value)
        keys.append(key)

    if not values:
        raise RuntimeError(f'В колонке высоты файла {path} нет ни одного числа.')

    values = np.asarray(values, dtype=np.float64)
    targets = np.asarray(frame_ids, dtype=np.float64) + 1.0   # 1-based, как в MATLAB

    if i_frame is not None and all(k is not None for k in keys):
        key_arr = np.asarray(keys, dtype=np.float64)
        order = np.argsort(key_arr)
        key_arr, values = key_arr[order], values[order]
        # Если ключ - время, а не номер кадра, приводим его к диапазону кадров.
        if 0 < key_arr.max() < 0.9 * targets.max():
            lo, hi = key_arr.min(), key_arr.max()
            span = (hi - lo) if hi > lo else 1.0
            key_arr = targets.min() + (key_arr - lo) / span * (targets.max() - targets.min())
        return np.interp(targets, key_arr, values)

    if len(values) == len(targets):
        return values                                  # по одному на кадр обработки
    if len(values) >= int(targets.max()):
        return values[(targets - 1).astype(int)]       # по одному на кадр источника

    print(f'[ПРЕДУПРЕЖДЕНИЕ] В файле высот {len(values)} значений на '
          f'{int(targets.max())} кадров - выборка растянута на весь диапазон.')
    src = np.linspace(targets.min(), targets.max(), len(values))
    return np.interp(targets, src, values)


def altitude_source(cfg):
    """
    Каноническое имя источника высоты: 'const' или 'file'.

    Синонимы приводятся здесь и только здесь, иначе разные места программы
    начинают понимать одно и то же значение по-разному: именно так 'vo'
    когда-то принимался при загрузке, но игнорировался в цикле, и высота
    молча оставалась постоянной.
    """
    src = str(((cfg.get('Altitude') or {}).get('Source', 'const'))).strip().lower()
    if src in ('file', 'csv', 'txt'):
        return 'file'
    if src in ('const', 'constant', 'value', 'number', ''):
        return 'const'
    if src in ('scale', 'vo'):
        raise RuntimeError(
            "ALTITUDE_SOURCE = 'scale' ('vo') больше не поддерживается: "
            'высота из масштаба сцены накапливала дрейф в разы за полёт '
            '(на ровном полёте 330 -> 73 м). Задайте высоту числом '
            "(ALTITUDE_SOURCE = 'const') или по кадрам из файла "
            "(ALTITUDE_SOURCE = 'file').")
    raise RuntimeError(
        f'Неизвестное ALTITUDE_SOURCE = "{src}". '
        "Допустимы 'const' (число) и 'file' (по кадрам из файла).")


def load_altitude_series(cfg, num_frames):
    """
    Высота съёмки для КАЖДОГО кадра источника, метры.

    Здесь высота - это масштаб: отрезок длиной L метров на земле занимает
    L * f / H пикселей, поэтому от неё напрямую зависят путь и скорость.
    Массив строится на все кадры источника, а не только на обрабатываемые,
    потому что при адаптивном выборе заранее неизвестно, какие это будут.

      'const' - постоянная ALTITUDE_VALUE;
      'file'  - значение на каждый кадр из ALTITUDE_FILE.

    Массив есть всегда: источника, дающего None, больше нет.
    """
    settings = cfg.get('Altitude') or {}
    source = altitude_source(cfg)

    if source == 'const':
        value = settings.get('Value')
        if value is None:
            raise RuntimeError(
                "Для ALTITUDE_SOURCE = 'const' задайте ALTITUDE_VALUE.")
        print(f'Высота: постоянная, {float(value):.3f} м')
        return np.full(int(num_frames), float(value))

    if source == 'file':
        if not settings.get('File'):
            raise RuntimeError(
                "Для ALTITUDE_SOURCE = 'file' задайте ALTITUDE_FILE.")
        alt = _read_altitude_file(cfg, list(range(int(num_frames))))
        print(f'Высота: из файла {settings["File"]}, '
              f'диапазон {alt.min():.2f}..{alt.max():.2f} м')
        return np.asarray(alt, dtype=np.float64)

    raise RuntimeError(f'Не обработан источник высоты: {source}')


def _altitude_to_z(altitude, index):
    """
    Координата Z траектории, метры, отсчёт от высоты первого кадра вверх.

    Ось направлена ВВЕРХ: траектория выдаётся в местной системе
    "восток - север - вверх", а не в системе камеры, смотрящей вниз.
    """
    return float(altitude[index]) - float(altitude[0])


def _turn_from_rotation(R):
    """Поворот вокруг вертикали из накопленной матрицы шага, радианы."""
    R = np.asarray(R, dtype=np.float64)
    if R.shape != (3, 3) or not np.all(np.isfinite(R)):
        return 0.0
    return float(math.atan2(R[1, 0], R[0, 0]))


def _pick_algorithm(cfg, algorithm=None):
    """
    Связка для построения траектории: первая из ALGORITHMS.

    Имя связки - это пара «детектор-дескриптор», написанная целиком.
    """
    chosen = select_algorithms(cfg) if algorithm is None else None
    if algorithm is not None:
        names = parse_algorithms(algorithm) or []
        if not names:
            raise RuntimeError('Не указана связка детектор-дескриптор.')
        available = get_algorithms()
        by_name = {a['Name'].lower(): a for a in available}
        item = by_name.get(names[0].lower())
        if item is None:
            have = ', '.join(a['Name'] for a in available)
            raise RuntimeError(
                f'Связка "{names[0]}" недоступна в этой сборке. Доступны: {have}')
        return item

    if not chosen:
        raise RuntimeError(
            'Не выбрано ни одной связки детектор-дескриптор. Проверьте '
            'ALGORITHMS и то, что OpenCV собран с нужными модулями: '
            'pip install opencv-contrib-python')
    return chosen[0]


