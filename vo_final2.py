def save_match_figure(image1, image2, points1, points2, filename, title, cfg):
    """
    Порт saveMatchFigure.m (showMatchedFeatures ... 'montage').

    Два кадра рядом, соответствия соединены линиями. Рисуется средствами
    OpenCV, чтобы не зависеть от matplotlib.
    """
    os.makedirs(os.path.dirname(filename) or '.', exist_ok=True)

    h1, w1 = image1.shape[:2]
    h2, w2 = image2.shape[:2]
    h = max(h1, h2)
    canvas = np.zeros((h, w1 + w2, 3), dtype=np.uint8)
    canvas[:h1, :w1] = cv2.cvtColor(image1, cv2.COLOR_GRAY2BGR) \
        if image1.ndim == 2 else image1
    canvas[:h2, w1:w1 + w2] = cv2.cvtColor(image2, cv2.COLOR_GRAY2BGR) \
        if image2.ndim == 2 else image2

    p1 = np.asarray(points1, dtype=np.float64).reshape(-1, 2)
    p2 = np.asarray(points2, dtype=np.float64).reshape(-1, 2)
    n = min(len(p1), len(p2))

    # Больше 300 линий превращают картинку в кашу - как и в MATLAB-версии
    # показываем подмножество, о чём честно пишем в подписи.
    step = max(1, n // 300)
    shown = 0
    for i in range(0, n, step):
        a = (int(round(p1[i, 0])), int(round(p1[i, 1])))
        b = (int(round(p2[i, 0])) + w1, int(round(p2[i, 1])))
        cv2.line(canvas, a, b, (0, 200, 255), 1, cv2.LINE_AA)
        cv2.circle(canvas, a, 3, (60, 255, 60), 1, cv2.LINE_AA)
        cv2.circle(canvas, b, 3, (60, 255, 60), 1, cv2.LINE_AA)
        shown += 1

    caption = f'{title} | показано {shown} из {n}'
    cv2.rectangle(canvas, (0, 0), (canvas.shape[1], 34), (0, 0, 0), -1)
    cv2.putText(canvas, caption, (10, 23), cv2.FONT_HERSHEY_SIMPLEX, 0.6,
                (255, 255, 255), 1, cv2.LINE_AA)
    cv2.imwrite(filename, canvas)


