def run_visual_odometry(cfg, sequence=None, algorithm=None, verbose=True):
    """
    Возвращает (rows, positions, rotations, frame_ids).

    Весь консольный вывод прогона дублируется в console_log.txt в папке
    метода - там же, где графики и trajectory.csv.
    """
    log = ConsoleLog().start()
    try:
        return _run_visual_odometry_body(cfg, sequence, algorithm, verbose, log)
    finally:
        log.stop()


def _run_visual_odometry_body(cfg, sequence, algorithm, verbose, log):
    """
    Возвращает (rows, positions, rotations, frame_ids).

    rows      - список словарей, колонки TRAJECTORY_COLUMNS
    positions - (n, 3) траектория В МЕТРАХ
    rotations - (n, 3, 3) накопленные повороты
    frame_ids - какие кадры источника были обработаны (0-based)
    """
    if sequence is None:
        sequence = open_sequence(cfg['DataFolder'], cfg)

    total = len(sequence)
    limit = (total if cfg['MaxFrames'] == float('inf')
             else int(min(total, cfg['MaxFrames'])))
    if limit < 2:
        raise RuntimeError(f'Требуется не менее двух кадров, доступно {limit}.')

    first_raw = sequence.read(0)
    if first_raw is None:
        raise RuntimeError('Не удалось прочитать первый кадр источника.')
    calib = load_calibration(cfg, first_raw.shape)
    frame_w = float(calib.Intrinsics.image_size[0])

    alg = _pick_algorithm(cfg, algorithm)
    vo_folder = os.path.join(cfg['ResultsFolder'], 'visual_odometry',
                             safe_file_name(alg['Name']))
    match_folder = os.path.join(vo_folder, 'matches')
    os.makedirs(match_folder, exist_ok=True)
    log.set_path(_console_log_path(cfg, vo_folder))

    if verbose:
        print(f'Метод визуальной одометрии: {alg["Name"]}')
        if calib.IsApproximate:
            print('[ПРЕДУПРЕЖДЕНИЕ] Используется приближенная калибровка. '
                  'Масштаб траектории будет неверен - см. FOCAL_LENGTH и '
                  'SCALE_CORRECTION в начале файла.')

    try:
        runner = AlgorithmRunner(alg, cfg)
    except Exception as exc:
        raise RuntimeError(
            f'Метод {alg["Name"]} недоступен: {_short_reason(exc)}') from exc

    # ------------------------------------------------------------- высота
    altitude = load_altitude_series(cfg, limit)
    alt_source = altitude_source(cfg)

    # Отбраковка единичных выбросов длины шага (см. STEP_LENGTH_LIMIT).
    step_limit = float((cfg.get('VO') or {}).get('StepLengthLimit', 0.0) or 0.0)
    num_clamped = 0

    # ------------------------------------------------- выбор кадров и обрезка
    sel = FrameSelector(cfg, frame_w)
    crop = RotationCrop(cfg)
    crop_toggled = 0
    if verbose:
        print(sel.describe())
        if crop.enabled:
            left, right, top, bottom = crop.rotation_cut
            print(f'Обрезка на поворотах: порог '
                  f'{math.degrees(crop.threshold):.1f} град/с, задержка '
                  f'{crop.delay} шагов, остаётся '
                  f'{100 * (1 - left - right) * (1 - top - bottom):.0f}% кадра')
        if cfg['Motion']['ShiftFrom'] == 'median' and crop.enabled:
            print("[ПРЕДУПРЕЖДЕНИЕ] SHIFT_FROM = 'median' вместе с обрезкой "
                  'занижает путь: несимметричные поля смещают медиану потока.')

    # ------------------------------------------------------------ состояние
    geom = cfg['Geometry']
    x_m, y_m = (float(v) for v in geom['InitialCoords'])
    heading = math.radians(float(geom['InitialHeadingDeg']))
    R_abs = _rot_z(heading)
    fps = float(getattr(sequence, 'fps', 0.0) or
                (cfg.get('Export') or {}).get('FrameRate', 25.0))
    distance_m = 0.0

    perf = cfg.get('Perf') or {}
    profile = bool(perf.get('Profile'))
    verbose_frames = bool(perf.get('VerbosePerFrame', True))
    save_figures = bool(perf.get('SaveMatchFigures', True))
    stage = {k: 0.0 for k in ('чтение кадров', 'предобработка', 'детектирование',
                              'сопоставление', 'оценка движения',
                              'картинки соответствий')}
    model_counts = {}
    saved_figures = 0
    retries = 0

    prev_id = 0
    prev_image = preprocess_frame(first_raw, calib, cfg)
    prev_data = detect_and_describe(prev_image, runner, cfg, crop)

    frame_ids = [0]
    positions = [(x_m, y_m, _altitude_to_z(altitude, 0))]
    rotations = [R_abs.copy()]
    rows = [{
        'Frame': 1, 'File': sequence.name(0),
        'X': x_m, 'Y': y_m, 'Z': float(positions[0][2]),
        'Altitude': float(altitude[0]),
        'SpeedMps': 0.0,
        'HeadingDeg': (90.0 - math.degrees(heading)) % 360.0,
        'TurnDeg': 0.0, 'StepM': 0.0, 'ShiftPct': 0.0, 'FrameStep': 0,
        'Matches': 0, 'Inliers': 0, 'InlierRatioPct': 0.0,
        'StepTimeMs': 0.0, 'Status': 'origin', 'Model': '',
        'RotationMode': int(crop.active),
        'UsedFramePct': 100.0 * crop.crop_fraction(),
    }]

    live = LiveTrajectoryPlot(cfg)
    viewer = FrameViewer(cfg)

    run_start = time.perf_counter()

    # -------------------------------------------------------------- главный цикл
    while True:
        curr_id = prev_id + sel.step
        if curr_id >= limit:
            # До конца остался неполный шаг: берём последний доступный кадр,
            # если он достаточно далеко от предыдущего.
            if limit - 1 - prev_id < max(1, sel.step // 4):
                break
            curr_id = limit - 1

        loop_start = time.perf_counter()
        t_stage = time.perf_counter()
        curr_raw = sequence.read(curr_id)
        stage['чтение кадров'] += time.perf_counter() - t_stage
        if curr_raw is None:
            print(f'Источник закончился на кадре {curr_id + 1}.')
            break

        t_stage = time.perf_counter()
        curr_image = preprocess_frame(curr_raw, calib, cfg)
        stage['предобработка'] += time.perf_counter() - t_stage

        t_stage = time.perf_counter()
        curr_data = detect_and_describe(curr_image, runner, cfg, crop)
        stage['детектирование'] += time.perf_counter() - t_stage

        t_stage = time.perf_counter()
        match_result = match_feature_sets(prev_data, curr_data, cfg)
        stage['сопоставление'] += time.perf_counter() - t_stage

        motion = empty_motion_result()
        pairs = match_result['IndexPairs']
        num_matches = len(pairs)
        alt_here = float(altitude[curr_id])

        if num_matches >= int(cfg['Ransac']['MinMatches']):
            matched1 = prev_data['Points'][pairs[:, 0]]
            matched2 = curr_data['Points'][pairs[:, 1]]
            t_stage = time.perf_counter()
            motion = estimate_motion(matched1, matched2, calib.Intrinsics,
                                     cfg, alt_here)
            stage['оценка движения'] += time.perf_counter() - t_stage
        else:
            motion['Message'] = 'too_few_matches'

        # --- Неудача: отступаем назад по шагу и пробуем ближний кадр ---------
        # Так алгоритм сам подстраивается под резкий манёвр или потерю
        # перекрытия, вместо того чтобы записать пропущенный шаг.
        if not motion['Success'] and sel.can_shrink():
            sel.shrink()
            retries += 1
            if verbose and verbose_frames:
                print(f'  кадр {curr_id + 1}: {motion["Message"]}, '
                      f'уменьшаю шаг до {sel.step}')
            continue

        # ------------------------------------------------------- накопление
        shift_px = 0.0
        step_m = 0.0
        if motion['Success']:
            model_counts[motion['Model']] = model_counts.get(motion['Model'], 0) + 1

            # Смещение сцены берётся по самим точкам, а не выводится из длины
            # шага: у существенной матрицы длина шага - условная единица, и
            # регулятор на ней слепнет. Медиана по инлаерам устойчива к
            # оставшимся выбросам. Считается ДО длины шага, потому что служит
            # ещё и независимой оценкой этой длины.
            mask = motion['InlierMask']
            if mask is not None and np.count_nonzero(mask) >= 3:
                d = matched2[mask] - matched1[mask]
            else:
                d = matched2 - matched1
            shift_px = float(np.median(np.hypot(d[:, 0], d[:, 1])))

            step_len = motion.get('StepLength')
            if step_len is None:
                # Эпиполярная модель без метрики: длина шага неизвестна,
                # берём условную единицу TRANSLATION_SCALE.
                step_len = float(cfg['VO']['TranslationScale'])
            elif step_limit > 0 and shift_px > 1e-6:
                # Сцена сместилась на shift_px пикселей - значит камера прошла
                # около shift_px * H / f метров. Оценка грубая (в смещение
                # входит и поворот), но независимая от модели и от истории.
                bound = (step_limit * shift_px * float(alt_here)
                         * float(cfg['Geometry']['ScaleCorrection'])
                         / max(calib.Intrinsics.fx, 1e-9))
                if float(step_len) > bound:
                    step_len = bound
                    num_clamped += 1

            step_vec = float(step_len) * motion['Translation']
            delta = R_abs @ step_vec
            x_m += float(delta[0])
            y_m += float(delta[1])
            step_m = float(math.hypot(delta[0], delta[1]))
            distance_m += step_m
            R_abs = orthonormalize_rotation(R_abs @ motion['Rotation'])
            heading = math.atan2(R_abs[1, 0], R_abs[0, 0])

            if (save_figures
                    and saved_figures < int(cfg['VO']['MaxSavedMatchFigures'])):
                saved_figures += 1
                mask = motion['InlierMask']
                t_stage = time.perf_counter()
                save_match_figure(
                    prev_image, curr_image, matched1[mask], matched2[mask],
                    os.path.join(match_folder, f'frame_{curr_id + 1:06d}.png'),
                    f'{alg["Name"]}, кадры {prev_id + 1}-{curr_id + 1}', cfg)
                stage['картинки соответствий'] += time.perf_counter() - t_stage

        turn_rad = _turn_from_rotation(motion['Rotation']) if motion['Success'] else 0.0
        dt = (curr_id - prev_id) / fps if fps > 0 else 0.0

        # Слишком резкий манёвр для такого шага: берём кадр ближе. Инлаеры
        # формально есть, но общая часть кадров мала и оценка ненадёжна.
        if motion['Success'] and sel.too_sharp(turn_rad, dt) and sel.can_shrink():
            sel.shrink()
            retries += 1
            if verbose and verbose_frames:
                print(f'  кадр {curr_id + 1}: поворот '
                      f'{math.degrees(abs(turn_rad)) / max(dt, 1e-9):.0f} град/с '
                      f'слишком резкий, уменьшаю шаг до {sel.step}')
            continue

        # Снимок обрезки, действовавшей ПРИ ОБРАБОТКЕ этого кадра: состояние
        # обновляется ниже, и окно должно показывать именно то, с чем искались
        # точки, а не то, что будет на следующем шаге.
        used_pct = 100.0 * crop.crop_fraction()
        was_active = crop.active
        crop_used = (was_active, crop.bounds(curr_image.shape),
                     crop.crop_fraction())
        crop.update(turn_rad, dt)
        if crop.enabled and crop.active != was_active:
            crop_toggled += 1
        z_m = _altitude_to_z(altitude, curr_id)
        frame_ids.append(curr_id)
        positions.append((x_m, y_m, z_m))
        rotations.append(R_abs.copy())
        rows.append({
            'Frame': curr_id + 1, 'File': sequence.name(curr_id),
            'X': x_m, 'Y': y_m, 'Z': float(z_m),
            'Altitude': float(alt_here),
            'SpeedMps': (step_m / dt) if dt > 0 else 0.0,
            'HeadingDeg': (90.0 - math.degrees(heading)) % 360.0,
            'TurnDeg': math.degrees(turn_rad),
            'StepM': step_m,
            'ShiftPct': 100.0 * shift_px / frame_w,
            'FrameStep': curr_id - prev_id,
            'Matches': int(num_matches),
            'Inliers': int(motion['NumInliers']),
            'InlierRatioPct': 100.0 * motion['InlierRatio'],
            'StepTimeMs': 1000.0 * (time.perf_counter() - loop_start),
            'Status': motion['Message'],
            'Model': motion['Model'],
            'RotationMode': int(was_active),
            'UsedFramePct': used_pct,
        })

        shown = False
        done = time.perf_counter() - run_start
        rate = (len(rows) - 1) / max(done, 1e-6)
        if verbose and verbose_frames:
            pct = 100.0 * (curr_id + 1) / max(limit, 1)
            shown = log.progress(
                f'[{pct:5.1f}%] кадр {curr_id + 1}/{limit}  шаг {curr_id - prev_id:3d}'
                f'  смещ {100 * shift_px / frame_w:4.1f}%'
                f'  инлаеров {motion["NumInliers"]:4d}'
                f'  путь {distance_m:7.1f} м'
                f'  {rate:5.1f} шаг/с')
        # Обновляемая строка работает только в терминале. Если вывод
        # перенаправлен в файл, печатаем сводку раз в полсотни шагов -
        # иначе о ходе работы не осталось бы ничего.
        if verbose and not shown and len(rows) % 50 == 0:
            print(f'Кадр {curr_id + 1}/{limit}: шагов {len(rows) - 1}, '
                  f'путь {distance_m:.0f} м, {rate:.1f} шаг/с')

        # Управление шагом по измеренному смещению
        sel.update(shift_px, turn_rad, dt, motion['Success'])

        live.update(positions, len(rows) - 1, distance_m)

        if viewer.enabled:
            keep = viewer.show(
                curr_image, curr_data.get('Points'),
                matched1 if motion['Success'] else None,
                matched2 if motion['Success'] else None,
                motion['InlierMask'] if motion['Success'] else None,
                crop_used,
                {'frame': curr_id + 1, 'limit': limit,
                 'step': curr_id - prev_id,
                 'shift': 100 * shift_px / frame_w,
                 'points': curr_data['NumValid'],
                 'matches': num_matches,
                 'inliers': motion['NumInliers'],
                 'rate': math.degrees(abs(turn_rad)) / max(dt, 1e-9),
                 'distance': distance_m,
                 'rate_steps': rate})
            if not keep:
                print('Прервано пользователем (q).')
                break

        prev_id, prev_image, prev_data = curr_id, curr_image, curr_data
        if curr_id >= limit - 1:
            break

    log.end_progress()
    viewer.close()
    live.update(positions, len(rows) - 1, distance_m, force=True)
    live.finish()

    n = len(rows)
    positions = np.asarray(positions, dtype=np.float64)
    rotations = np.asarray(rotations, dtype=np.float64)

    # -------------------------------------------------------------- сохранение
    write_table(rows, os.path.join(vo_folder, 'trajectory.csv'),
                TRAJECTORY_COLUMNS)
    save_mat(os.path.join(vo_folder, 'trajectory.mat'),
             positions=positions,
             rotations=np.transpose(rotations, (1, 2, 0)),
             frameIds=np.asarray([i + 1 for i in frame_ids]),
             algorithm=alg['Name'],
             scaleCorrection=float(cfg['Geometry']['ScaleCorrection']))
    plot_trajectory(positions, vo_folder, alg['Name'], cfg)
    write_gps_track(positions, frame_ids, fps, vo_folder, cfg,
                    np.array([r['Altitude'] for r in rows]))

    # ---------------------------------------------------------------- сводка
    steps = max(n - 1, 1)
    elapsed = time.perf_counter() - run_start
    speeds = [float(r['SpeedMps']) for r in rows[1:] if r['Status'].startswith('ok')]
    used_steps = [int(r['FrameStep']) for r in rows[1:] if r['FrameStep'] > 0]
    shifts = [float(r['ShiftPct']) for r in rows[1:] if r['ShiftPct'] > 0]
    turns = [abs(float(r['TurnDeg'])) for r in rows[1:]]

    print(f'Путь {distance_m:.1f} м, средняя скорость '
          f'{(sum(speeds) / len(speeds)) if speeds else 0.0:.2f} м/с, '
          f'конечная точка X={x_m:.1f} м, Y={y_m:.1f} м')
    if num_clamped:
        print(f'Ограничение длины шага сработало на {num_clamped} шагах из '
              f'{len(rows) - 1}: длина превышала оценку по смещению сцены '
              f'более чем в {step_limit:g} раза. Единичные срабатывания '
              f'нормальны; если их много, масштаб шага восстанавливается '
              f'неустойчиво - проверьте модель движения и калибровку.')

    print(f'Высота ({alt_source}): '
          f'{min(r["Altitude"] for r in rows):.1f}..'
          f'{max(r["Altitude"] for r in rows):.1f} м, '
          f'поправка масштаба {cfg["Geometry"]["ScaleCorrection"]:g}')

    if used_steps:
        print(f'Шаг по кадрам: {min(used_steps)}..{max(used_steps)} '
              f'(медиана {int(np.median(used_steps))}), смещение сцены '
              f'медиана {np.median(shifts) if shifts else 0.0:.1f} % кадра, '
              f'отступов назад {retries}')
    if crop.enabled:
        rates = [abs(float(r['TurnDeg'])) / max(float(r['FrameStep']) / fps, 1e-9)
                 for r in rows[1:] if r['FrameStep'] > 0]
        print(f'Режим поворота: активен на {crop.steps_active} шагах из {steps} '
              f'({100.0 * crop.steps_active / steps:.1f} %), переключений '
              f'{crop_toggled}; угловая скорость - медиана '
              f'{np.median(rates) if rates else 0.0:.2f}, максимум '
              f'{max(rates) if rates else 0.0:.2f} град/с')
    print(f'Обработано шагов: {steps} за {elapsed:.1f} с '
          f'({steps / max(elapsed, 1e-6):.2f} шаг/с) из {limit} кадров источника')
    if model_counts:
        parts = ', '.join(f'{k}: {v}' for k, v in sorted(model_counts.items()))
        print(f'Модель движения по шагам - {parts}')
    if profile:
        total_stage = sum(stage.values()) or 1e-9
        print('Время по этапам (на обработанный кадр):')
        for name, sec in sorted(stage.items(), key=lambda kv: -kv[1]):
            if sec > 0:
                print(f'  {name:<24s} {sec / steps * 1000:8.1f} мс '
                      f'{100 * sec / total_stage:5.1f} %')

    if verbose:
        print(f'Траектория сохранена в {vo_folder}')

    if (cfg.get('Visualization') or {}).get('ShowPlots'):
        plt = _pyplot(cfg)
        if plt is not None:
            print('Окна с графиками открыты - закройте их, чтобы продолжить.')
            plt.ioff()
            plt.show()

    return rows, positions, rotations, frame_ids








