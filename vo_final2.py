def _detect_harris(gray, cfg):
    """
    detectHarrisFeatures(I, 'MinQuality', q, 'FilterSize', s).

    MinQuality отсчитывается от МАКСИМУМА отклика по кадру - именно это
    свойство и делало заливку OSD обязательной.
    """
    f = cfg['Features']
    block = int(f.get('HarrisFilterSize', 5))
    resp = cv2.cornerHarris(gray.astype(np.float32), block, 3,
                            float(f.get('HarrisK', 0.04)))
    peak = float(resp.max())
    if peak <= 0:
        return []
    threshold = float(f.get('HarrisMinQuality', 0.01)) * peak

    # Локальный максимум 3x3 - аналог non-max suppression в MATLAB
    local_max = resp >= cv2.dilate(resp, np.ones((3, 3), np.uint8))
    ys, xs = np.nonzero((resp > threshold) & local_max)
    size = float(f.get('DefaultKeypointSize', 7.0))
    return [cv2.KeyPoint(float(x), float(y), size, -1.0, float(resp[y, x]))
            for x, y in zip(xs, ys)]


def _detect_fast(gray, cfg):
    """
    detectFASTFeatures(I, 'MinQuality', q).

    MATLAB применяет два порога: MinContrast (абсолютный, доля от 255) и
    MinQuality (относительный, доля от максимума метрики угла). OpenCV FAST
    знает только абсолютный, поэтому относительный накладывается вручную.
    """
    f = cfg['Features']
    abs_threshold = max(1, int(round(float(f.get('FastMinContrast', 0.1)) * 255)))
    detector = cv2.FastFeatureDetector_create(threshold=abs_threshold,
                                              nonmaxSuppression=True)
    kps = detector.detect(gray, None)
    if not kps:
        return []
    resp = np.array([k.response for k in kps], dtype=np.float64)
    threshold = float(f.get('FastMinQuality', 0.05)) * resp.max()
    return [k for k, r in zip(kps, resp) if r >= threshold]


_ORB_CACHE = {}


def _make_orb(cfg, image_shape=None):
    """
    ORB с параметрами MATLAB detectORBFeatures.

    MATLAB - обёртка над cv::ORB::create (builtins/src/ocv/detectORBCore.cpp),
    поэтому при одинаковых параметрах точки совпадают. Значения взяты из
    getDefaultParameters в detectORBFeatures.m:
        NumFeatures   = число пикселей кадра (фактически без ограничения)
        ScaleFactor   = 1.2      NumLevels     = 8
        EdgeThreshold = 31       FirstLevel    = 0
        SamplingPairs = 2        PatchSize     = 31
        FastThreshold = 20       ScoreType     = 0 (Harris)
    Отличался именно NumFeatures: ограничение сверху меняет отбор по уровням
    пирамиды и давало 18 529 точек вместо 28 718 у MATLAB.
    """
    f = cfg['Features']
    if f.get('OrbMatchMatlab', True) and image_shape is not None:
        n_features = int(image_shape[0]) * int(image_shape[1])
    else:
        n_features = int(f.get('OrbMaxDetect', 20000))

    key = (n_features, float(f.get('OrbScaleFactor', 1.2)),
           int(f.get('OrbNumLevels', 8)))
    orb = _ORB_CACHE.get(key)
    if orb is None:
        orb = cv2.ORB_create(nfeatures=key[0], scaleFactor=key[1], nlevels=key[2],
                             edgeThreshold=31, firstLevel=0, WTA_K=2,
                             scoreType=cv2.ORB_HARRIS_SCORE, patchSize=31,
                             fastThreshold=20)
        _ORB_CACHE[key] = orb
    return orb


def build_detector(name, cfg):
    """Возвращает функцию detect(gray) -> список cv2.KeyPoint."""
    name = name.upper()
    f = cfg['Features']

    if name == 'HARRIS':
        return lambda gray: _detect_harris(gray, cfg)
    if name == 'FAST':
        return lambda gray: _detect_fast(gray, cfg)
    if name == 'ORB':
        # Число точек зависит от размера кадра, поэтому объект создаётся,
        # когда кадр уже известен (кэшируется в _ORB_CACHE).
        return lambda gray: list(_make_orb(cfg, gray.shape).detect(gray, None))
    factory = feature_factory(name)
    if factory is None:
        raise ValueError(f'Детектор {name} отсутствует в этой сборке OpenCV')

    if name == 'KAZE':
        impl = factory(threshold=float(f.get('KazeThreshold', 0.0005)))
    elif name == 'AKAZE':
        impl = factory(threshold=float(f.get('KazeThreshold', 0.0005)))
    elif name == 'SURF':
        impl = factory(hessianThreshold=float(f.get('SurfMetricThreshold', 500)))
    else:
        impl = factory()
    return lambda gray: list(impl.detect(gray, None))


def build_descriptor(name, cfg):
    """Возвращает объект с методом compute(gray, keypoints)."""
    name = name.upper()
    f = cfg['Features']
    if name == 'ORB':
        return _make_orb(cfg)

    factory = feature_factory(name)
    if factory is None:
        raise ValueError(f'Дескриптор {name} отсутствует в этой сборке OpenCV')

    if name in ('KAZE', 'AKAZE'):
        return factory(threshold=float(f.get('KazeThreshold', 0.0005)))
    if name == 'SURF':
        return factory(hessianThreshold=float(f.get('SurfMetricThreshold', 500)))
    return factory()


class AlgorithmRunner:
    """
    Детектор и дескриптор одной связки, созданные один раз.

    В MATLAB объекты пересоздавались на каждом кадре внутри
    detectAndDescribe; здесь они переиспользуются - результат тот же,
    но заметно быстрее.
    """

    def __init__(self, alg, cfg):
        self.alg = alg
        self.cfg = cfg
        self.detect = build_detector(alg['Detector'], cfg)
        self.descriptor = build_descriptor(alg['Descriptor'], cfg)
        self.is_binary = is_binary(alg['Descriptor'])


def empty_feature_data():
    return {'Points': np.zeros((0, 2), np.float32), 'Features': None,
            'IsBinary': False, 'NumDetected': 0, 'NumValid': 0,
            'NumRejectedOsd': 0,
        'NumRejectedCrop': 0, 'TimeSec': 0.0, 'Message': 'ok'}


def detect_and_describe(image, runner, cfg, crop=None):
    """
    Порт detectAndDescribe.m.

    Возвращает словарь с точками (Nx2, координаты OpenCV, 0-based),
    дескрипторами и счётчиками.

    crop - объект RotationCrop или None. Если режим поворота включён, точки
    из краевых полос отбрасываются ДО отбора selectUniform, чтобы сетка
    отбора распределяла точки по оставшейся части кадра, а не по всему кадру.
    """
    data = empty_feature_data()
    data['IsBinary'] = runner.is_binary
    t0 = time.perf_counter()

    try:
        keypoints = runner.detect(image)
        data['NumDetected'] = len(keypoints)
        if not keypoints:
            data['Message'] = 'no_points'
            data['TimeSec'] = time.perf_counter() - t0
            return data

        keypoints, data['NumRejectedOsd'] = reject_osd_points(keypoints, cfg)
        if not keypoints:
            data['Message'] = 'no_points_outside_osd'
            data['TimeSec'] = time.perf_counter() - t0
            return data

        keypoints, data['NumRejectedCrop'] = reject_cropped_points(
            keypoints, crop, image.shape)
        if not keypoints:
            data['Message'] = 'no_points_inside_crop'
            data['TimeSec'] = time.perf_counter() - t0
            return data

        max_features = min(int(cfg['Features']['MaxFeatures']), len(keypoints))
        if cfg['Features'].get('SelectUniform', True):
            keypoints = select_uniform(keypoints, max_features, image.shape)
        else:
            keypoints = select_strongest(keypoints, max_features)

        valid_points, features = runner.descriptor.compute(image, keypoints)
        if features is None or len(valid_points) == 0:
            data['Message'] = 'no_descriptors'
            data['TimeSec'] = time.perf_counter() - t0
            return data

        data['Points'] = cv2.KeyPoint_convert(valid_points).astype(np.float32)
        data['Features'] = features
        data['NumValid'] = len(valid_points)

    except cv2.error as exc:
        data['Message'] = f'error: {exc}'
    except Exception as exc:                       # как catch ME в MATLAB
        data['Message'] = f'error: {exc}'

    data['TimeSec'] = time.perf_counter() - t0
    return data


