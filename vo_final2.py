def safe_mean(values):
    """Среднее по конечным значениям (порт safeMean.m)."""
    v = np.asarray(list(values), dtype=np.float64).ravel()
    v = v[np.isfinite(v)]
    return float(np.mean(v)) if v.size else float('nan')


