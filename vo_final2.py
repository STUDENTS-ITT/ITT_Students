# ##   8. СОПОСТАВЛЕНИЕ ДЕСКРИПТОРОВ  (+vo/matchFeatureSets.m)                ##
# ############################################################################

# Порт +vo/matchFeatureSets.m
# Этапы 6-7 алгоритма: поиск ближайших дескрипторов и отсев неоднозначных
# соответствий (ratio test + взаимная уникальность).
# О ПОРОГЕ MatchThreshold
# -----------------------
# В MATLAB MatchThreshold задаётся В ПРОЦЕНТАХ от максимально возможного
# расстояния между дескрипторами, а не в абсолютных единицах:
#   * бинарные дескрипторы (метрика Hamming): максимум = число бит,
#     порог = BinaryThreshold / 100 * numBits.        60 % от 256 бит = 153.6
#   * вещественные (метрика SSD, векторы нормируются): максимум ||a-b||^2 = 4
#     при единичной норме, порог = FloatThreshold / 100 * 4.   10 % -> 0.4
# Точная внутренняя нормировка MATLAB не документирована, поэтому формулы
# вынесены сюда явно: если сравнение с MATLAB покажет систематическое
# расхождение по числу соответствий, крутить надо именно их.
# Ratio test применяется к ТОЙ ЖЕ метрике, что и порог. Для SSD это отношение
# КВАДРАТОВ расстояний - MaxRatio 0.75 по квадратам соответствует ~0.87 по
# обычным расстояниям (классический критерий Лоу).


def _normalize_rows(features):
    f = np.asarray(features, dtype=np.float32)
    norms = np.linalg.norm(f, axis=1, keepdims=True)
    np.maximum(norms, 1e-12, out=norms)
    return f / norms


def _prepare(features, is_binary, cfg):
    """Дескрипторы в виде, пригодном для BFMatcher, и максимум расстояния."""
    if is_binary:
        f = np.ascontiguousarray(features, dtype=np.uint8)
        return f, 8.0 * f.shape[1]                    # максимум = число бит
    f = np.asarray(features, dtype=np.float32)
    if cfg['Matching'].get('NormalizeFloatFeatures', True):
        f = _normalize_rows(f)
        max_dist = 4.0 if cfg['Matching'].get('SquaredFloatMetric', True) else 2.0
    else:
        max_dist = float(np.inf)                      # порог фактически отключён
    return np.ascontiguousarray(f), max_dist


def _to_metric(distances, is_binary, cfg):
    """BFMatcher возвращает Hamming или L2; MATLAB для float использует SSD."""
    if is_binary:
        return distances
    if cfg['Matching'].get('SquaredFloatMetric', True):
        return distances ** 2
    return distances


def match_feature_sets(data1, data2, cfg):
    """
    Порт matchFeatureSets.m.

    Возвращает словарь с IndexPairs (Nx2, индексы точек в data1 и data2),
    Metric, MedianMetric, TimeSec, Message.
    """
    result = {'IndexPairs': np.zeros((0, 2), dtype=int), 'Metric': None,
              'MedianMetric': float('nan'), 'TimeSec': 0.0, 'Message': 'ok'}

    if data1['NumValid'] == 0 or data2['NumValid'] == 0:
        result['Message'] = 'empty_features'
        return result

    t0 = time.perf_counter()
    try:
        is_binary = bool(data1['IsBinary'])
        f1, max_dist = _prepare(data1['Features'], is_binary, cfg)
        f2, _ = _prepare(data2['Features'], is_binary, cfg)

        norm = cv2.NORM_HAMMING if is_binary else cv2.NORM_L2
        matcher = cv2.BFMatcher_create(norm, crossCheck=False)

        n1, n2 = len(f1), len(f2)
        keep = np.zeros(n1, dtype=bool)
        best = np.zeros(n1, dtype=int)
        best_d = np.full(n1, np.inf)
        second_d = np.full(n1, np.inf)

        knn = matcher.knnMatch(f1, f2, k=min(2, n2))
        for i, pair in enumerate(knn):
            if not pair:
                continue
            best[i] = pair[0].trainIdx
            best_d[i] = pair[0].distance
            if len(pair) > 1:
                second_d[i] = pair[1].distance

        best_metric = _to_metric(best_d, is_binary, cfg)
        second_metric = _to_metric(second_d, is_binary, cfg)

        # --- абсолютный порог (MatchThreshold, % от максимума) ---
        threshold_pct = (cfg['Matching']['BinaryThreshold'] if is_binary
                         else cfg['Matching']['FloatThreshold'])
        abs_threshold = float(threshold_pct) / 100.0 * max_dist
        if is_binary:
            # percentToLevel.m: для Хемминга порог округляется до целых бит
            abs_threshold = float(np.round(abs_threshold))
        keep = np.isfinite(best_metric) & (best_metric <= abs_threshold)

        # --- ratio test (MaxRatio) ---
        max_ratio = float(cfg['Matching']['MaxRatio'])
        with np.errstate(divide='ignore', invalid='ignore'):
            # findUnambiguousMatches.m: если второе расстояние ~0, отношение = 1
            near_zero = second_metric < 1e-6
            ratio = np.where(second_metric > 0, best_metric / second_metric, 1.0)
            ratio[near_zero] = 1.0
        ratio[~np.isfinite(second_metric)] = 0.0      # единственный кандидат
        keep &= ratio <= max_ratio

        # --- взаимная уникальность (Unique) ---
        if cfg['Matching'].get('Unique', True):
            reverse = matcher.match(f2, f1)
            reverse_best = np.full(n2, -1, dtype=int)
            for m in reverse:
                reverse_best[m.queryIdx] = m.trainIdx
            keep &= reverse_best[best] == np.arange(n1)

        idx1 = np.nonzero(keep)[0]
        result['IndexPairs'] = np.column_stack([idx1, best[idx1]])
        metric = best_metric[idx1]
        result['Metric'] = metric
        if metric.size:
            result['MedianMetric'] = float(np.median(metric))

    except cv2.error as exc:
        result['Message'] = f'error: {exc}'
    except Exception as exc:
        result['Message'] = f'error: {exc}'

    result['TimeSec'] = time.perf_counter() - t0
    return result


