# Порт run_all_visual_odometry.m
# Построение траекторий всеми доступными алгоритмами и их сравнение
# на одном графике.


TRAJECTORY_SUMMARY_COLUMNS = ['Algorithm', 'NumFrames', 'SuccessfulSteps', 'MeanMatches',
                   'MeanInliers', 'MeanInlierRatioPct', 'PathLength',
                   'FinalX', 'FinalY', 'FinalZ', 'ElapsedSec']


def run_all_visual_odometry(cfg, verbose=True):
    algorithms = select_algorithms(cfg)
    if not algorithms:
        raise RuntimeError('Нет доступных алгоритмов детектирования/описания.')
    if (cfg.get('VO') or {}).get('Algorithms'):
        print('Отобрано методов: '
              + ', '.join(a['Name'] for a in algorithms))

    compare_folder = os.path.join(cfg['ResultsFolder'], 'visual_odometry',
                                  'comparison')
    os.makedirs(compare_folder, exist_ok=True)
    with ConsoleLog(_console_log_path(cfg, compare_folder)):
        return _run_all_visual_odometry_body(cfg, verbose, algorithms,
                                             compare_folder)


def _run_all_visual_odometry_body(cfg, verbose, algorithms, compare_folder):
    cfg['VO']['MaxSavedMatchFigures'] = min(
        int(cfg['VO']['MaxSavedMatchFigures']), 2)

    # Источник открывается один раз на все методы - для видео это критично.
    sequence = open_sequence(cfg['DataFolder'], cfg)
    if not getattr(sequence, 'length_known', True):
        print('[ПРЕДУПРЕЖДЕНИЕ] Источник не поддерживает перемотку назад, '
              'поэтому прогнать по нему несколько методов подряд нельзя.')
        print('                 Используйте --mode vo (один метод) или '
              'скачайте видео в файл.')

    alg_names, positions_list, rows = [], [], []
    print(f'\n=== ТРАЕКТОРИИ ДЛЯ {len(algorithms)} АЛГОРИТМОВ ===')

    for i, alg in enumerate(algorithms, start=1):
        name = alg['Name']
        print(f'\n--- [{i}/{len(algorithms)}] {name} ---')
        t0 = time.perf_counter()
        try:
            traj_rows, positions, _, _ = run_visual_odometry(
                cfg, sequence=sequence, algorithm=name, verbose=False)
        except Exception as exc:
            print(f'[ПРЕДУПРЕЖДЕНИЕ] {name} пропущен: {_short_reason(exc)}')
            continue
        elapsed = time.perf_counter() - t0

        alg_names.append(name)
        positions_list.append(positions)

        steps_ok = sum(1 for r in traj_rows if str(r['Status']).startswith('ok'))
        d = np.diff(positions, axis=0)
        path_length = float(np.sum(np.linalg.norm(d, axis=1)))
        tail = traj_rows[1:]

        rows.append({
            'Algorithm': name,
            'NumFrames': len(traj_rows),
            'SuccessfulSteps': steps_ok,
            'MeanMatches': safe_mean([r['Matches'] for r in tail]),
            'MeanInliers': safe_mean([r['Inliers'] for r in tail]),
            'MeanInlierRatioPct': safe_mean(
                [r['InlierRatioPct'] for r in tail]),
            'PathLength': path_length,
            'FinalX': float(positions[-1, 0]),
            'FinalY': float(positions[-1, 1]),
            'FinalZ': float(positions[-1, 2]),
            'ElapsedSec': elapsed,
        })

        print(f'Готово за {elapsed:.1f} с: успешных шагов '
              f'{steps_ok}/{len(traj_rows) - 1}, длина пути {path_length:.2f}')

    write_table(
        rows, os.path.join(compare_folder, 'trajectory_summary.csv'),
        TRAJECTORY_SUMMARY_COLUMNS)
    save_mat(
        os.path.join(compare_folder, 'all_trajectories.mat'),
        algNames=np.array(alg_names, dtype=object),
        **{f'positions_{safe_file_name(n)}': p
           for n, p in zip(alg_names, positions_list)})
    plot_trajectory_comparison(alg_names, positions_list,
                                        compare_folder, cfg)

    if verbose:
        print()
        print_table(rows, TRAJECTORY_SUMMARY_COLUMNS)
        print(f'\nСравнительные графики: {compare_folder}')
    return rows


