def print_table(rows, columns=None, float_fmt='{:.2f}'):
    """Аналог disp(table) - выравненный вывод в консоль."""
    if not rows:
        print('(пусто)')
        return
    columns = list(columns or rows[0].keys())
    cells = [[_cell(r.get(c, ''), float_fmt) for c in columns] for r in rows]
    widths = [max(len(str(c)), *(len(row[i]) for row in cells))
              for i, c in enumerate(columns)]
    print('  '.join(str(c).ljust(w) for c, w in zip(columns, widths)))
    print('  '.join('-' * w for w in widths))
    for row in cells:
        print('  '.join(v.ljust(w) for v, w in zip(row, widths)))


def _cell(value, float_fmt):
    if isinstance(value, (bool, np.bool_)):
        return str(bool(value))
    if isinstance(value, (float, np.floating)):
        return 'NaN' if not np.isfinite(value) else float_fmt.format(float(value))
    return str(value)


