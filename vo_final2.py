class FrameViewer:
    """
    Окно с обрабатываемым видеопотоком.

    Показывает ровно то, с чем работает алгоритм: кадр ПОСЛЕ предобработки -
    в яркости, с залитой экранной графикой, - а поверх него отобранные точки,
    инлаеры со следами смещения и границу обрезки на поворотах.

    Окно не влияет на расчёт: если сборка OpenCV без графики (пакет
    opencv-python-headless), режим сам отключается с предупреждением.
    """

    DIM = 0.35            # во сколько раз гасится отброшенная обрезкой область

    def __init__(self, cfg):
        vis = cfg.get('Visualization') or {}
        self.enabled = bool(vis.get('ShowVideo'))
        self.width = int(vis.get('VideoWidth', 1100))
        self.draw_points = bool(vis.get('VideoPoints', True))
        self.draw_tracks = bool(vis.get('VideoTracks', True))
        self.dim_cropped = bool(vis.get('VideoDim', True))
        self.paused = False
        self.stop = False
        # Латиницей: заголовки окон OpenCV на Windows тоже не принимают
        # кириллицу и показывают знаки вопроса.
        self.window = 'Visual odometry - current frame'
        if not self.enabled:
            return
        try:
            cv2.namedWindow(self.window, cv2.WINDOW_NORMAL)
            cv2.resizeWindow(self.window, self.width, int(self.width * 9 / 16))
        except cv2.error as exc:
            print(f'[ПРЕДУПРЕЖДЕНИЕ] Окно OpenCV недоступно ({_short_reason(exc)}); '
                  'просмотр видеопотока выключен. Нужен пакет '
                  'opencv-contrib-python вместо opencv-python-headless.')
            self.enabled = False

    def show(self, image, points, matched1, matched2, inliers, crop_used, info):
        """
        image     - кадр после предобработки (полутоновый);
        points    - все отобранные точки текущего кадра, Nx2;
        matched1  - сопоставленные точки ПРЕДЫДУЩЕГО кадра, Mx2;
        matched2  - они же в текущем кадре, Mx2;
        inliers   - булева маска инлаеров длины M;
        crop_used - (была ли обрезка, границы, доля площади) НА ЭТОМ кадре;
        info      - словарь строк для сводки.

        Возвращает False, если пользователь просит прервать прогон.
        """
        active, bounds, fraction = crop_used
        if not self.enabled:
            return True
        try:
            vis = cv2.cvtColor(image, cv2.COLOR_GRAY2BGR)

            # Область, отброшенная обрезкой, гасится - сразу видно, что
            # алгоритм на этом шаге не использует.
            if self.dim_cropped and active:
                x0, x1, y0, y1 = (int(v) for v in bounds)
                mask = np.ones(vis.shape[:2], dtype=bool)
                mask[y0:y1, x0:x1] = False
                vis[mask] = (vis[mask] * self.DIM).astype(np.uint8)
                cv2.rectangle(vis, (x0, y0), (x1 - 1, y1 - 1), (60, 200, 255), 2)

            # Все отобранные точки - синие: это «сырьё» детектора. Серым по
            # серому кадру их было бы не разглядеть, поэтому цвет контрастный.
            # Те, что останутся синими, сопоставить не удалось.
            if self.draw_points and points is not None and len(points):
                for x, y in points.astype(int):
                    cv2.circle(vis, (x, y), 2, (235, 160, 50), -1)

            # Сопоставленные: инлаеры зелёные, отбракованные красные.
            if matched2 is not None and len(matched2):
                mask = (inliers if inliers is not None
                        else np.ones(len(matched2), dtype=bool))
                for (x2, y2), ok in zip(matched2.astype(int), mask):
                    cv2.circle(vis, (x2, y2), 3,
                               (80, 220, 80) if ok else (60, 60, 230), -1)
                if self.draw_tracks and matched1 is not None:
                    for (x1p, y1p), (x2, y2), ok in zip(
                            matched1.astype(int), matched2.astype(int), mask):
                        if ok:
                            cv2.line(vis, (x1p, y1p), (x2, y2), (80, 220, 80), 1)

            scale = self.width / vis.shape[1]
            if scale < 1.0:
                vis = cv2.resize(vis, (self.width, int(vis.shape[0] * scale)),
                                 interpolation=cv2.INTER_AREA)
            self._hud(vis, info, active, fraction)

            cv2.imshow(self.window, vis)
            delay = 0 if self.paused else 1
            key = cv2.waitKey(delay) & 0xFF
            if key == ord('q'):
                self.stop = True
                return False
            if key == ord(' '):
                self.paused = not self.paused
            return True
        except cv2.error:
            self.enabled = False          # окно закрыли - просто перестаём рисовать
            return True

    def _hud(self, vis, info, crop_active, crop_fraction):
        """
        Тёмная плашка со сводкой в левом верхнем углу.

        Текст ЛАТИНИЦЕЙ: встроенные шрифты OpenCV (FONT_HERSHEY_*) содержат
        только ASCII, и кириллица выводится знаками вопроса. Рисовать русский
        пришлось бы через PIL с внешним шрифтом - ради четырёх строк в окне
        это лишняя зависимость.
        """
        rows = [
            f'frame {info["frame"]}/{info["limit"]}   step {info["step"]}'
            f'   shift {info["shift"]:.1f} % of frame',
            f'points {info["points"]}   matches {info["matches"]}'
            f'   inliers {info["inliers"]}',
            f'turn {info["rate"]:.1f} deg/s'
            + ('   CROP ON: %.0f %% of frame' % (100 * crop_fraction)
               if crop_active else '   crop off'),
            f'path {info["distance"]:.0f} m   {info["rate_steps"]:.1f} steps/s'
            + ('   PAUSED (space)' if self.paused else '   q - quit'),
        ]
        pad, line = 8, 20
        h = pad * 2 + line * len(rows)
        panel = vis[0:h, 0:520]
        vis[0:h, 0:520] = (panel * 0.35).astype(np.uint8)
        for i, text in enumerate(rows):
            cv2.putText(vis, text, (pad, pad + line * (i + 1) - 5),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.45, (235, 235, 235), 1,
                        cv2.LINE_AA)

    def close(self):
        if self.enabled:
            try:
                cv2.destroyWindow(self.window)
            except cv2.error:
                pass


class LiveTrajectoryPlot:
    """
    Окно с траекторией, обновляемое по ходу работы.

    Артисты создаются один раз, дальше только set_data - это на порядок
    дешевле, чем перерисовывать оси целиком. Если окно открыть не удалось
    (нет графической среды, не тот backend), режим молча отключается: прогон
    важнее картинки.
    """

    def __init__(self, cfg):
        vis = cfg.get('Visualization') or {}
        self.every = max(1, int(vis.get('LivePlotEvery', 10)))
        self.ok = False
        self.plt = None
        if not vis.get('LivePlot'):
            return
        plt = _pyplot(cfg)
        if plt is None:
            return
        try:
            plt.ion()
            self.fig, self.ax = plt.subplots(figsize=(7, 6))
            self.line, = self.ax.plot([], [], '-', color='#c0392b', lw=1.2)
            self.head, = self.ax.plot([], [], 'o', color='#c0392b', ms=6)
            self.ax.set_xlabel('восток, м')
            self.ax.set_ylabel('север, м')
            self.ax.grid(alpha=0.3)
            self.ax.set_aspect('equal', 'datalim')
            # Заголовок ставится до tight_layout, иначе места под него
            # не резервируется и он обрезается сверху.
            self.ax.set_title('ожидание первых шагов')
            self.fig.tight_layout()
            self.fig.show()
            self.plt = plt
            self.ok = True
        except Exception as exc:                       # noqa: BLE001
            print(f'[ПРЕДУПРЕЖДЕНИЕ] Живой график недоступен ({exc}); '
                  'работа продолжается без него.')
            self.ok = False

    def update(self, positions, step_index, distance_m, force=False):
        """positions - список (x, y, z) в метрах."""
        if not self.ok:
            return
        if not force and step_index % self.every:
            return
        try:
            xs = [p[0] for p in positions]
            ys = [p[1] for p in positions]
            self.line.set_data(xs, ys)
            self.head.set_data(xs[-1:], ys[-1:])
            self.ax.set_title(f'шагов {len(positions) - 1}, путь {distance_m:.0f} м')
            self.ax.relim()
            self.ax.autoscale_view()
            self.fig.canvas.draw_idle()
            self.fig.canvas.flush_events()
        except Exception:                              # noqa: BLE001
            # Окно закрыли руками - просто перестаём рисовать.
            self.ok = False

    def finish(self):
        """Оставить окно на экране, если просили показать графики."""
        if self.ok and self.plt is not None:
            try:
                self.fig.canvas.draw_idle()
                self.fig.canvas.flush_events()
            except Exception:                          # noqa: BLE001
                pass


