# Порт +vo/loadCalibration.m
# ВАЖНОЕ ОТЛИЧИЕ ОТ MATLAB
# ------------------------
# MATLAB сохраняет калибровку как ОБЪЕКТ класса cameraIntrinsics или
# cameraParameters. scipy.io.loadmat такие объекты прочитать не может - они
# приходят как непрозрачный MatlabOpaque. Поэтому поддерживаются:
#   * .json  - {"fx":..., "fy":..., "cx":..., "cy":..., "image_size":[h,w],
#               "distortion":[k1,k2,p1,p2,k3]}
#   * .npz   - те же ключи
#   * .mat   - только с ЧИСЛОВЫМИ переменными (fx, fy, cx, cy, K, ...),
#              не с объектом cameraIntrinsics
# Чтобы выгрузить калибровку из MATLAB в читаемый вид:
#     K = intrinsics.K;  imageSize = intrinsics.ImageSize;
#     save('camera_calibration.mat','K','imageSize','-v7');
# СИСТЕМА КООРДИНАТ
# -----------------
# MATLAB нумерует пиксели с 1: центр левого верхнего пикселя = (1,1).
# OpenCV нумерует с 0. Поэтому главная точка MATLAB (cx_m, cy_m) равна
# (cx_m - 1, cy_m - 1) в OpenCV. Приближённая калибровка MATLAB
# principal = [(w+1)/2, (h+1)/2] превращается в [(w-1)/2, (h-1)/2].


class Intrinsics:
    """Внутренние параметры камеры (аналог cameraIntrinsics)."""

    def __init__(self, fx, fy, cx, cy, image_size, distortion=None):
        self.fx = float(fx)
        self.fy = float(fy)
        self.cx = float(cx)
        self.cy = float(cy)
        self.image_size = (int(image_size[0]), int(image_size[1]))   # (h, w)
        self.distortion = (np.zeros(5, dtype=np.float64) if distortion is None
                           else np.asarray(distortion, dtype=np.float64).ravel())

    @property
    def K(self):
        return np.array([[self.fx, 0.0, self.cx],
                         [0.0, self.fy, self.cy],
                         [0.0, 0.0, 1.0]], dtype=np.float64)

    def scaled(self, image_size):
        """Масштабирование под другой размер кадра (как в loadCalibration.m)."""
        h, w = image_size
        sy = h / self.image_size[0]
        sx = w / self.image_size[1]
        return Intrinsics(self.fx * sx, self.fy * sy,
                          self.cx * sx, self.cy * sy, (h, w), None)

    def __repr__(self):
        return (f'Intrinsics(fx={self.fx:.2f}, fy={self.fy:.2f}, '
                f'cx={self.cx:.2f}, cy={self.cy:.2f}, '
                f'size={self.image_size[1]}x{self.image_size[0]})')


class Calibration:
    def __init__(self, intrinsics, is_approximate=False, source=''):
        self.Intrinsics = intrinsics
        self.IsApproximate = is_approximate
        self.Source = source

    @property
    def has_distortion(self):
        return not np.allclose(self.Intrinsics.distortion, 0.0)


def _from_mapping(data, image_size):
    """Собирает Intrinsics из словаря с числовыми полями."""
    def get(*names):
        for n in names:
            if n in data:
                return data[n]
        return None

    K = get('K', 'IntrinsicMatrix', 'camera_matrix', 'cameraMatrix')
    dist = get('distortion', 'dist', 'distCoeffs', 'RadialDistortion')
    size = get('image_size', 'imageSize', 'ImageSize')
    if size is not None:
        size = np.asarray(size).ravel()
        size = (int(size[0]), int(size[1]))
    else:
        size = image_size

    if K is not None:
        K = np.asarray(K, dtype=np.float64).reshape(3, 3)
        # MATLAB хранит IntrinsicMatrix транспонированной (строчная запись).
        if abs(K[0, 2]) < 1e-9 and abs(K[2, 0]) > 1e-9:
            K = K.T
        return Intrinsics(K[0, 0], K[1, 1], K[0, 2], K[1, 2], size, dist)

    fx = get('fx', 'FocalLengthX')
    fy = get('fy', 'FocalLengthY')
    focal = get('focal', 'FocalLength')
    if fx is None and focal is not None:
        focal = np.asarray(focal).ravel()
        fx, fy = focal[0], focal[-1]
    cx = get('cx', 'PrincipalPointX')
    cy = get('cy', 'PrincipalPointY')
    pp = get('principal', 'PrincipalPoint')
    if cx is None and pp is not None:
        pp = np.asarray(pp).ravel()
        cx, cy = pp[0], pp[1]

    if fx is None or cx is None:
        return None
    return Intrinsics(float(fx), float(fy if fy is not None else fx),
                      float(cx), float(cy), size, dist)


def _load_file(path, image_size):
    ext = os.path.splitext(path)[1].lower()

    if ext == '.json':
        with open(path, 'r', encoding='utf-8') as fh:
            return _from_mapping(json.load(fh), image_size)

    if ext == '.npz':
        with np.load(path) as data:
            return _from_mapping({k: data[k] for k in data.files}, image_size)

    if ext == '.mat':
        try:
            import scipy.io as sio
        except ImportError:
            print('[ПРЕДУПРЕЖДЕНИЕ] Для чтения .mat нужен scipy: pip install scipy')
            return None
        raw = sio.loadmat(path, squeeze_me=True, struct_as_record=False)
        data = {k: v for k, v in raw.items() if not k.startswith('__')}
        opaque = [k for k, v in data.items()
                  if type(v).__name__ == 'MatlabOpaque']
        result = _from_mapping(data, image_size)
        if result is None and opaque:
            print('[ПРЕДУПРЕЖДЕНИЕ] В файле калибровки лежат MATLAB-объекты '
                  f'({", ".join(opaque)}), которые scipy читать не умеет.')
            print('                 Пересохраните числа: '
                  "save('camera_calibration.mat','K','imageSize','-v7')")
        return result

    print(f'[ПРЕДУПРЕЖДЕНИЕ] Неизвестный формат калибровки: {path}')
    return None


def load_calibration(cfg, raw_image_shape):
    """
    Загрузка или создание внутренних параметров камеры.

    raw_image_shape - shape массива кадра, (h, w) или (h, w, 3).
    """
    image_size = (int(raw_image_shape[0]), int(raw_image_shape[1]))
    camera = cfg['Camera']
    intrinsics = None
    source = ''

    path = camera.get('CalibrationFile')
    if path and os.path.exists(path):
        intrinsics = _load_file(path, image_size)
        if intrinsics is not None:
            source = path

    if intrinsics is None and camera.get('FocalLength') and camera.get('PrincipalPoint'):
        focal = np.asarray(camera['FocalLength'], dtype=np.float64).ravel()
        pp = np.asarray(camera['PrincipalPoint'], dtype=np.float64).ravel()
        intrinsics = Intrinsics(focal[0], focal[-1], pp[0], pp[1], image_size,
                                camera.get('DistortionCoeffs'))
        source = 'vo_config.py'

    is_approximate = False
    if intrinsics is None:
        if not camera.get('AllowApproximate', True):
            raise RuntimeError(
                'Калибровка не задана. Укажите CalibrationFile или '
                'FocalLength/PrincipalPoint в vo_config.py.')
        h, w = image_size
        focal = camera.get('ApproximateFocalFactor', 0.9) * max(image_size)
        # MATLAB: [(w+1)/2, (h+1)/2] в 1-based -> то же самое в 0-based:
        intrinsics = Intrinsics(focal, focal, (w - 1) / 2.0, (h - 1) / 2.0,
                                image_size, None)
        is_approximate = True
        source = 'approximate'
        print('[ПРЕДУПРЕЖДЕНИЕ] Реальные параметры камеры не найдены. Создана '
              'приближенная калибровка; количественная точность траектории '
              'не гарантируется.')

    if intrinsics.image_size != image_size:
        print('[ПРЕДУПРЕЖДЕНИЕ] Размер изображения отличается от размера '
              'калибровки. Внутренние параметры масштабированы, коррекция '
              'дисторсии отключена.')
        intrinsics = intrinsics.scaled(image_size)

    calib = Calibration(intrinsics, is_approximate, source)
    print(f'Калибровка: {intrinsics} (источник: {source})')
    return calib


