def write_table(rows, path, columns=None):
    """Аналог writetable: CSV с заголовком и фиксированным порядком колонок."""
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    if not rows:
        return
    columns = list(columns or rows[0].keys())
    with open(path, 'w', encoding='utf-8', newline='') as fh:
        writer = csv.DictWriter(fh, fieldnames=columns, extrasaction='ignore')
        writer.writeheader()
        for row in rows:
            writer.writerow({c: _fmt(row.get(c, '')) for c in columns})


def _fmt(value):
    if isinstance(value, (bool, np.bool_)):
        return int(value)
    if isinstance(value, (float, np.floating)):
        if not np.isfinite(value):
            return 'NaN'
        return f'{float(value):.15g}'
    return value


def save_mat(path, **arrays):
    """
    Аналог save(...): результаты в .mat, читаемые из MATLAB.

    Таблицы MATLAB (table) в .mat не пишутся - вместо них сохраняются
    числовые массивы, а таблица лежит рядом в CSV.
    """
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    try:
        import scipy.io as sio
        sio.savemat(path, arrays, do_compression=True)
        return True
    except ImportError:
        np.savez_compressed(os.path.splitext(path)[0] + '.npz', **arrays)
        print('[ПРЕДУПРЕЖДЕНИЕ] scipy не установлен, сохранил .npz вместо .mat')
        return False


