def apply_speed_preset(cfg, name=None):
    """
    Ставит параметры оценки движения по имени предустановки.

    Нелинейное уточнение не отключается ни в одной из них: оно стоит около
    9 мс на шаг, но без него направление переноса расходится с эталоном на
    12.5 градуса вместо 2.6 - это самая выгодная точность за единицу времени
    во всём конвейере.

    Потолок детектирования ORB снижается только в 'fast'. Замер на 9 кадрах:
    порог W*H (как в MATLAB) - 22874 точки и 25.8 мс на кадр, порог 4000 -
    18.1 мс, причём соответствий становится БОЛЬШЕ (859 против 587) и
    инлаеров тоже (815 против 562): отбор оставляет более сильные и лучше
    разнесённые точки. Для остальных предустановок значение не трогается,
    чтобы сохранить совпадение с MATLAB по числу детектированных точек.
    """
    name = str(name if name is not None else cfg['Perf']['Preset']).lower()
    preset = SPEED_PRESETS.get(name)
    if preset is not None:
        for section, values in preset.items():
            cfg[section].update(values)
        cfg['Perf']['Preset'] = name
    return cfg

