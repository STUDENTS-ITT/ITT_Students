#ifndef TYPES_H
#define TYPES_H

// =============================================================================
// types.h — базовые типы и физические константы проекта БИНС
//
// Содержит:
//   - Физические константы (параметры Земли)
//   - Векторные и матричные типы (Vec3, Mat3)
//   - Структуры данных навигации (NavState, IMU_Record, Nav_Record)
// =============================================================================

#include <cmath>

// ---------------------------------------------------------------------------
// Физические константы
// ---------------------------------------------------------------------------

const double GM_EARTH = 3.986004418e14;  // Гравитационный параметр Земли (м³/с²)
const double R_EQ = 6378137.0;           // Экваториальный радиус Земли (м)
const double U_EARTH = 7.292115e-5;      // Угловая скорость вращения Земли (рад/с)
const double PI = 3.14159265358979323846; // Число π

// ---------------------------------------------------------------------------
// Вектор и матрица 3×3
// ---------------------------------------------------------------------------

/** Трёхмерный вектор. Используется для координат, скоростей, углов, ускорений. */
struct Vec3 { double x, y, z; };

/** Матрица 3×3. Используется для матрицы направляющих косинусов (МНК). */
struct Mat3 { double data[3][3]; };

// ---------------------------------------------------------------------------
// Состояние навигации (NavState)
// ---------------------------------------------------------------------------

/**
 * Полное состояние БИНС на текущий момент времени.
 *
 * Системы координат:
 *   pos  — широта (x), долгота (y), высота (z): радианы / метры
 *   vel  — Север (x), Вверх (y), Восток (z): м/с
 *   euler — рыскание (x), тангаж (y), крен (z): радианы
 *   C    — матрица направляющих косинусов (географическая → связанная)
 *   accel, gyro — последние показания датчиков (связанная система)
 */
struct NavState {
    double T_sys, T_reg, T_rem, T_nav; // Временные метки фаз
    Vec3 pos;       // {Lat, Lon, Alt} — положение (рад, м)
    Vec3 vel;       // {North, Up, East} — скорость (м/с)
    Vec3 euler;     // {Yaw, Pitch, Roll} — углы ориентации (рад)
    Mat3 C;         // Матрица направляющих косинусов (гео → связанная)
    Vec3 accel;     // {Ax, Ay, Az} — акселерометр (м/с²)
    Vec3 gyro;      // {Wx, Wy, Wz} — гироскоп (рад/с)
};

// ---------------------------------------------------------------------------
// Запись IMU (один сэмпл)
// ---------------------------------------------------------------------------

/** Один сэмпл данных инерциального датчика (IMU). */
struct IMU_Record {
    double Time;       // Временная метка (с)
    double Ax, Ay, Az; // Проекции ускорения (м/с²) в связанной системе
    double Wx, Wy, Wz; // Проекции угловой скорости (град/с) в связанной системе
};

// ---------------------------------------------------------------------------
// Запись навигации (Nav.dat)
// ---------------------------------------------------------------------------

/**
 * Строка из файла Nav.dat + вычисленная граница выставки.
 *
 * Файл Nav.dat содержит временной ряд фаз:
 *   T_sys  — системное время (с)
 *   T_reg  — время регулировки (с)
 *   T_rem  — оставшееся время до конца фазы (с)
 *   T_nav  — время навигации (с); T_nav > 0 означает переход в навигацию
 *   Lon, Lat, Alt — координаты (градусы, метры)
 *
 * alignment_end_T — T_sys последней строки с T_nav == 0 (конец выставки)
 */
struct Nav_Record {
    double T_sys, T_reg, T_rem, T_nav;
    double Lon, Lat, Alt;
    double alignment_end_T;
};

#endif // TYPES_H
