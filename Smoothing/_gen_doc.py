    def footer(self):
        self.set_y(-15)
        self.set_font(F, "", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, "- " + str(self.page_no()) + " -", align="C")

    def h1(self, t):
        if self.get_y() > 240:
            self.add_page()
        self.set_font(F, "B", 15)
        self.set_text_color(26, 35, 126)
        self.ln(5)
        self.multi_cell(0, 8, t)
        self.set_draw_color(26, 35, 126)
        self.line(10, self.get_y() + 1, 200, self.get_y() + 1)
        self.ln(4)

    def h2(self, t):
        if self.get_y() > 255:
            self.add_page()
        self.set_font(F, "B", 12)
        self.set_text_color(40, 53, 147)
        self.ln(4)
        self.multi_cell(0, 7, t)
        self.ln(2)

    def h3(self, t):
        self.set_font(F, "BI", 10.5)
        self.set_text_color(57, 73, 171)
        self.ln(2)
        self.multi_cell(0, 6, t)
        self.ln(1)

    def txt(self, t):
        self.set_font(F, "", 10)
        self.set_text_color(34, 34, 34)
        self.multi_cell(0, 5.5, t)
        self.ln(1.5)

    def txtb(self, t):
        self.set_font(F, "B", 10)
        self.set_text_color(34, 34, 34)
        self.multi_cell(0, 5.5, t)
        self.ln(1.5)

    def formula(self, t):
        self.set_fill_color(248, 248, 250)
        self.set_draw_color(200, 200, 210)
        self.set_font(M, "", 9.5)
        self.set_text_color(34, 34, 34)
        lines = t.count("\n") + 1
        h = max(lines * 5, 7)
        if self.get_y() + h + 6 > 275:
            self.add_page()
        self.set_x(15)
        self.multi_cell(180, 5, t, fill=True, border=1)
        self.ln(2)

    def tbl(self, rows, col_widths=None):
        if not rows:
            return
        cols = max(len(r) for r in rows)
        if col_widths:
            widths = col_widths
        else:
            w = 180.0 / cols
            widths = [w] * cols
        needed = len(rows) * 6.5 + 8
        if self.get_y() + needed > 270:
            self.add_page()
        for ri, row in enumerate(rows):
            if ri == 0:
                self.set_font(F, "B", 8)
                self.set_fill_color(232, 234, 246)
            else:
                self.set_font(F, "", 8)
                self.set_fill_color(252, 252, 255) if ri % 2 else self.set_fill_color(245, 245, 248)
            self.set_text_color(34, 34, 34)
            self.set_draw_color(190, 190, 200)
            for ci, cell in enumerate(row):
                self.set_xy(10 + sum(widths[:ci]), self.get_y())
                s = str(cell)
                if len(s) > 60:
                    s = s[:57] + "..."
                self.cell(widths[ci], 6.5, s, border=1, fill=True)
            self.ln(6.5)
        self.ln(3)

    def ul(self, items):
        self.set_font(F, "", 10)
        self.set_text_color(34, 34, 34)
        for item in items:
            self.set_x(10)
            self.multi_cell(0, 5.5, "  -  " + item)
        self.ln(2)

    def sep(self):
        self.set_draw_color(180, 180, 190)
        self.line(30, self.get_y(), 180, self.get_y())
        self.ln(3)


