// tuner_configs.h — перечень конфигов подбора в каталоге тюнера.
//
// Вкладка «Подбор» показывает один список, из которого выбирается конфиг и
// для запуска tune_kalman.py, и для сборки PDF-отчёта. В каталоге тюнера
// лежат две группы конфигов:
//   * tuner_config*.json — штатные конфиги наборов dataset_shum;
//   * truth_cfg*/cfg_*.json — конфиги экспериментов «сравнение с истиной»
//     (13A/13B/13G), у них свой каталог на каждую серию.
// Разбор путей вынесен из виджета, чтобы его можно было проверить тестом.
//
// Зависимостей от Qt-виджетов нет — только QtCore (QString/QStringList/QDir).

#pragma once

#include <QString>
#include <QStringList>

namespace gui
{

// Возвращает относительные пути конфигов подбора в tuner_dir:
//   * tuner_config*.json из корня (кроме *smoke*),
//   * cfg_*.json из подкаталогов truth_cfg*.
// Список отсортирован: сначала корневые конфиги по имени, затем конфиги
// подкаталогов (подкаталоги по имени, внутри — по имени файла). Для пустого
// или несуществующего каталога возвращается пустой список.

QStringList listTunerConfigs(const QString &tuner_dir);

} // namespace gui
